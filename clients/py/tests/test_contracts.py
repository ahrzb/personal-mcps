async def test_fixture_ok_and_rejection_replies_drive_both_paths(registry) -> None:
    """§6 · the fixture's ok reply completes registration and its rejection reply
    raises RegistrationError — both replayed as the fixture gives them with only
    the OBSERVED request id filled in. A fixture pins no per-run value
    (contracts/README, "nothing that varies per run"), so neither reply carries
    an ``id``; a byte-for-byte replay correlates to no request, leaves
    registration unanswered until the 10 s deadline, and lands on close 4004 —
    reconnect, not RegistrationError. The refusal beside its allow-twin, both
    read from the fixture rather than hand-spelled."""
    # The ack the client is answered with is the fixture's own frame, not a
    # paraphrase the harness synthesizes: a change to its shape must reach this
    # client, which is the entire point of a shared oracle.
    accepting = await start_fake_hub(registrations=[RegisterOutcome(frame=_TUNNEL_FRAMES["register"]["ack"])])
    good = pmcp_client.HubTransport(accepting.origin, TOKEN)
    registry.append((accepting, good))
    await good.__aenter__()  # must not raise

    refusing = await start_fake_hub(registrations=[RegisterOutcome(frame=_TUNNEL_FRAMES["register"]["rejection"])])
    bad = pmcp_client.HubTransport(refusing.origin, TOKEN, {"All": []})
    registry.append((refusing, bad))
    with pytest.raises(pmcp_client.RegistrationError):
        await bad.__aenter__()


async def test_hub_replaced_notification_is_recognized_verbatim(registry) -> None:
    """§6 · the fixture's hub/replaced notification drives the stop-quietly path:
    the library recognizes the pinned frame, not a paraphrase of it."""
    hub = await start_fake_hub()
    transport = pmcp_client.HubTransport(hub.origin, TOKEN)
    registry.append((hub, transport))
    read_stream, _write_stream = await transport.__aenter__()
    await hub.next_frame(1)
    await hub.send(_TUNNEL_FRAMES["replaced"])
    await hub.close_connection(4000)
    # Recognized means CONSUMED: the pinned notification never reaches the
    # session, and the 4000 close it precedes stops this copy quietly — `closed()`
    # returning rather than raising IS the stop_quiet ending.
    with anyio.fail_after(5):
        await transport.closed()
    with pytest.raises(anyio.EndOfStream):
        await read_stream.receive()


async def test_hub_control_methods_equal_the_set_consumed_internally(registry) -> None:
    """§6 · the set of hub/* methods the fixture defines equals the set the
    transport consumes internally — a method outside that set reaches the SDK
    session untouched, so a new control frame cannot be swallowed silently."""
    assert sorted(pmcp_client.HUB_METHODS.values()) == sorted(_TUNNEL_FRAMES["methods"].values())
    hub = await start_fake_hub()
    transport = pmcp_client.HubTransport(hub.origin, TOKEN)
    registry.append((hub, transport))
    read_stream, _write_stream = await transport.__aenter__()
    stranger = {"jsonrpc": "2.0", "id": 3, "method": "hub/something-new", "params": {}}
    await hub.send(stranger)
    item = await read_stream.receive()
    assert item.message.model_dump(by_alias=True, exclude_unset=True) == stranger


def test_caller_reads_the_fixtures_forwarded_meta_keys() -> None:
    """§7 · the forwarded-call ``_meta`` keys :func:`caller` reads are the
    fixture's ``forwardedCall.metaKeys``, read FROM the fixture and never
    hand-spelled: hub/principal and hub/roles land on principal and roles, and
    the third pinned key (io.modelcontextprotocol/clientCapabilities) reaches the
    SDK session untouched. This is the one tunnel-frames key whose consumer is
    the client library, and renaming it hub-side must fail here — silently,
    caller() would start answering principal "" and empty roles, and every
    service branching on a negative check (``if not caller.has_role("admin"):
    allow``) would flip open. §7 invites services to trust these values, which is
    what makes an unread fixture key a boundary and not cosmetics."""
    principal_key, roles_key, capabilities_key = _TUNNEL_FRAMES["forwardedCall"]["metaKeys"]
    meta = {principal_key: "sa:claude", roles_key: ["reader"], capabilities_key: {"sampling": {}}}
    identity = caller(meta)
    assert identity.principal == "sa:claude"
    assert identity.roles == ("reader",)
    assert identity.has_role("reader") is True
